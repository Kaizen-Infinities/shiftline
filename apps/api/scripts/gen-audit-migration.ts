/**
 * Generates the append-only audit-trail migration (P0-13, MCA Companies
 * (Accounts) Rules 3(1)): a row-level trigger on every audited table writes
 * old/new JSON, actor, request id and tenant into audit_log inside the same
 * transaction as the change, and audit_log itself refuses UPDATE and DELETE
 * except from the retention sweep. Being database triggers, the trail cannot
 * be switched off by application code or configuration.
 *
 *   npx tsx scripts/gen-audit-migration.ts > prisma/migrations/<timestamp>_audit_trail/migration.sql
 *
 * Re-run after adding a model to AUDITED_MODELS and create a new migration.
 */
import { Prisma } from "@prisma/client";

/** Books of account, tax documents, payroll and the masters they depend on. */
export const AUDITED_MODELS = [
  // books
  "Voucher",
  "JournalItem",
  "AccountLedger",
  "AccountingPeriod",
  "BankAccount",
  "OpeningBalance",
  // documents
  "SalesInvoice",
  "SalesInvoiceItem",
  "SalesInvoicePayment",
  "GrnInvoice",
  "GrnInvoiceItem",
  "SalesReturn",
  "PurchaseReturn",
  "Expense",
  "PettyCashEntry",
  "StockAdjustment",
  // payroll
  "PayrollRun",
  "Payslip",
  "EmployeePayrollConfig",
  // masters
  "Company",
  "BusinessPlace",
  "InvoiceSetting",
  "Customer",
  "Supplier",
  "Product",
  "RawMaterial",
  "User",
  "Role",
  "RolePermission",
  "RetentionPolicy",
  "MobileCollection",
];

const models = Prisma.dmmf.datamodel.models;
const tables = AUDITED_MODELS.filter((name) => {
  const found = models.some((m) => m.name === name);
  if (!found) process.stderr.write(`skip: model ${name} not in schema\n`);
  return found;
}).map((name) => {
  const m = models.find((x) => x.name === name)!;
  const id = m.fields.find((f) => f.isId);
  const idColumn = id ? (id.dbName ?? id.name) : (m.primaryKey?.fields[0] ?? "id");
  return {
    table: m.dbName ?? m.name,
    idColumn,
    hasCompany: m.fields.some((f) => f.name === "companyId"),
  };
});

const out: string[] = [];
out.push(`-- Append-only audit trail (generated by scripts/gen-audit-migration.ts).`);
out.push(`-- Actor and request come from transaction-local settings written by lib/prisma.ts.`);
out.push(``);
out.push(
  `CREATE OR REPLACE FUNCTION audit_row() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER AS $$`
);
out.push(`DECLARE`);
out.push(`  v_old jsonb;`);
out.push(`  v_new jsonb;`);
out.push(`  v_action "AuditAction";`);
out.push(`  v_id text;`);
out.push(`  v_company uuid;`);
out.push(`  v_user text := NULLIF(current_setting('app.user_id', true), '');`);
out.push(`  v_admin bigint := NULLIF(current_setting('app.admin_id', true), '')::bigint;`);
out.push(`  v_request text := NULLIF(current_setting('app.request_id', true), '');`);
out.push(
  `  v_actor text := COALESCE(NULLIF(current_setting('app.actor_type', true), ''), 'system');`
);
out.push(`  v_impersonator text := NULLIF(current_setting('app.impersonated_by', true), '');`);
out.push(`BEGIN`);
out.push(`  IF TG_OP = 'INSERT' THEN`);
out.push(`    v_new := to_jsonb(NEW); v_action := 'CREATE';`);
out.push(`  ELSIF TG_OP = 'UPDATE' THEN`);
out.push(`    v_old := to_jsonb(OLD); v_new := to_jsonb(NEW); v_action := 'UPDATE';`);
out.push(`    IF v_old = v_new THEN RETURN NEW; END IF;`);
out.push(`  ELSE`);
out.push(`    v_old := to_jsonb(OLD); v_action := 'DELETE';`);
out.push(`  END IF;`);
out.push(`  v_id := COALESCE(v_new->>TG_ARGV[0], v_old->>TG_ARGV[0]);`);
out.push(`  IF TG_ARGV[1] = 'company' THEN`);
out.push(`    v_company := COALESCE(v_new->>'company_id', v_old->>'company_id')::uuid;`);
out.push(`  ELSIF TG_TABLE_NAME = 'companies' THEN`);
out.push(`    v_company := v_id::uuid;`);
out.push(`  END IF;`);
out.push(`  -- Secrets never enter the trail.`);
out.push(
  `  v_old := v_old - 'passwordHash' - 'password_hash' - 'sessionToken' - 'accessToken' - 'refreshToken';`
);
out.push(
  `  v_new := v_new - 'passwordHash' - 'password_hash' - 'sessionToken' - 'accessToken' - 'refreshToken';`
);
out.push(
  `  INSERT INTO audit_log (company_id, "entityName", "entityId", action, "oldValues", "newValues",`
);
out.push(
  `    "changedBy", "changedByAdmin", request_id, actor_type, impersonated_by, "changedAt")`
);
out.push(`  VALUES (v_company, TG_TABLE_NAME, v_id, v_action, v_old, v_new,`);
out.push(`    v_user, v_admin, v_request, v_actor, v_impersonator, now());`);
out.push(`  RETURN COALESCE(NEW, OLD);`);
out.push(`END $$;`);
out.push(``);
out.push(`-- audit_log is append-only: only the retention sweep (8-year floor) may remove rows.`);
out.push(`CREATE OR REPLACE FUNCTION audit_log_guard() RETURNS trigger LANGUAGE plpgsql AS $$`);
out.push(`BEGIN`);
out.push(
  `  IF COALESCE(current_setting('app.retention_sweep', true), 'off') = 'on' AND TG_OP = 'DELETE' THEN`
);
out.push(`    RETURN OLD;`);
out.push(`  END IF;`);
out.push(
  `  RAISE EXCEPTION 'audit_log is append-only (% refused)', TG_OP USING ERRCODE = 'insufficient_privilege';`
);
out.push(`END $$;`);
out.push(`DROP TRIGGER IF EXISTS audit_log_immutable ON audit_log;`);
out.push(
  `CREATE TRIGGER audit_log_immutable BEFORE UPDATE OR DELETE ON audit_log FOR EACH ROW EXECUTE FUNCTION audit_log_guard();`
);
out.push(``);
out.push(`DO $$ BEGIN`);
out.push(`  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'shiftline_app') THEN`);
out.push(`    REVOKE UPDATE, DELETE ON audit_log FROM shiftline_app;`);
out.push(`  END IF;`);
out.push(`END $$;`);
out.push(``);
for (const t of tables) {
  out.push(`DROP TRIGGER IF EXISTS audit_${t.table} ON "${t.table}";`);
  out.push(
    `CREATE TRIGGER audit_${t.table} AFTER INSERT OR UPDATE OR DELETE ON "${t.table}" FOR EACH ROW EXECUTE FUNCTION audit_row('${t.idColumn}', '${t.hasCompany ? "company" : "none"}');`
  );
}
process.stdout.write(out.join("\n") + "\n");
