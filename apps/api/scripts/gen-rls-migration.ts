/**
 * Generates the row-level-security migration from the Prisma schema so every
 * tenant table is covered. Run after adding tenant models, then create a new
 * migration folder with the output:
 *
 *   npx tsx scripts/gen-rls-migration.ts > prisma/migrations/<timestamp>_rls_<name>/migration.sql
 */
import { Prisma } from "@prisma/client";

const GLOBAL = new Set([
  "Company",
  "Admin",
  "Permission",
  "UserSession",
  "PasswordResetToken",
  "LoginAttempt",
]);

const tables = Prisma.dmmf.datamodel.models
  .filter((m) => !GLOBAL.has(m.name) && m.fields.some((f) => f.name === "companyId"))
  .map((m) => m.dbName ?? m.name)
  .sort();

const lines: string[] = [];
lines.push(
  `-- Row-level security for every tenant table (generated by scripts/gen-rls-migration.ts).`
);
lines.push(
  `-- The application sets app.company_id per transaction (lib/prisma.ts); platform paths set app.bypass_rls.`
);
lines.push(``);
lines.push(`CREATE OR REPLACE FUNCTION app_company_id() RETURNS uuid LANGUAGE sql STABLE AS $$`);
lines.push(`  SELECT NULLIF(current_setting('app.company_id', true), '')::uuid`);
lines.push(`$$;`);
lines.push(``);
lines.push(`CREATE OR REPLACE FUNCTION app_rls_bypass() RETURNS boolean LANGUAGE sql STABLE AS $$`);
lines.push(`  SELECT COALESCE(current_setting('app.bypass_rls', true), 'off') = 'on'`);
lines.push(`$$;`);
lines.push(``);
for (const t of tables) {
  lines.push(`ALTER TABLE "${t}" ENABLE ROW LEVEL SECURITY;`);
  lines.push(`ALTER TABLE "${t}" FORCE ROW LEVEL SECURITY;`);
  lines.push(`DROP POLICY IF EXISTS tenant_isolation ON "${t}";`);
  lines.push(
    `CREATE POLICY tenant_isolation ON "${t}" USING (company_id = app_company_id()) WITH CHECK (company_id = app_company_id());`
  );
  lines.push(`DROP POLICY IF EXISTS platform_bypass ON "${t}";`);
  lines.push(
    `CREATE POLICY platform_bypass ON "${t}" USING (app_rls_bypass()) WITH CHECK (app_rls_bypass());`
  );
  lines.push(``);
}
process.stdout.write(lines.join("\n"));
